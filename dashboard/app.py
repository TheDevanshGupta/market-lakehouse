"""Streamlit front-end over the gold (marts) layer. Read-only DuckDB connection."""

from __future__ import annotations

import os
from datetime import timedelta
from pathlib import Path

import duckdb
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

ROOT = Path(__file__).resolve().parents[1]
WAREHOUSE = Path(os.getenv("LAKEHOUSE_WAREHOUSE", ROOT / "data" / "warehouse.duckdb"))

# Categorical slots in fixed order (identity follows the series, never its rank).
SERIES = ["#2a78d6", "#eb6834", "#1baf7a"]
POSITIVE, NEGATIVE, NEUTRAL = "#2a78d6", "#e34948", "#898781"
STATUS_BAD = "#d03b3b"

st.set_page_config(page_title="Market Lakehouse", page_icon="📈", layout="wide")


@st.cache_data(ttl=300)
def q(sql: str, params: tuple = ()) -> pd.DataFrame:
    with duckdb.connect(str(WAREHOUSE), read_only=True) as con:
        return con.execute(sql, list(params)).df()


def style(fig: go.Figure, height: int = 360) -> go.Figure:
    fig.update_layout(
        height=height,
        margin=dict(l=8, r=8, t=36, b=8),
        hovermode="x unified",
        legend=dict(orientation="h", yanchor="bottom", y=1.0, xanchor="left", x=0, title=None),
    )
    fig.update_xaxes(showgrid=False, title=None)
    fig.update_yaxes(gridwidth=0.5, title=None, zeroline=False)
    fig.update_traces(selector=dict(type="scatter"), line_width=2)
    return fig


if not WAREHOUSE.exists():
    st.error(f"Warehouse not found at `{WAREHOUSE}`. Run `lakehouse run` first.")
    st.stop()

# ---------------------------------------------------------------- sidebar filters
bounds = q("select min(trade_date) lo, max(trade_date) hi from marts.fct_daily_prices").iloc[0]
lo, hi = bounds["lo"].date(), bounds["hi"].date()
st.sidebar.title("Market Lakehouse")
st.sidebar.caption("Bronze → Silver → Gold · dbt + DuckDB")
preset = st.sidebar.radio("Period", ["1M", "3M", "6M", "1Y", "All"], index=3, horizontal=True)
days = {"1M": 30, "3M": 91, "6M": 182, "1Y": 365}.get(preset)
start = max(lo, hi - timedelta(days=days)) if days else lo
sectors_all = q("select distinct sector from marts.dim_security order by 1")["sector"].tolist()
sectors = st.sidebar.multiselect("Sectors", sectors_all, default=sectors_all)
if not sectors:
    st.warning("Select at least one sector.")
    st.stop()
sector_ph = ",".join("?" * len(sectors))

st.title("Market Lakehouse")
st.info(
    "All companies and prices shown here are **fictional**, generated by the project's own "
    "simulator. They are not real market data and not investment advice.",
    icon="ℹ️",
)
st.caption(f"{start:%d %b %Y} → {hi:%d %b %Y} · data as of last successful pipeline run")

overview, drill, dq, about = st.tabs(
    ["Market overview", "Security drill-down", "Data quality", "Architecture"]
)

# ---------------------------------------------------------------- market overview
with overview:
    perf = q(
        f"""
        with px as (
            select f.symbol, s.company_name, s.sector, f.trade_date, f.close_price, f.turnover
            from marts.fct_daily_prices f join marts.dim_security s using (symbol)
            where f.trade_date between ? and ? and s.sector in ({sector_ph})
        )
        select symbol, company_name, sector,
               arg_max(close_price, trade_date) / arg_min(close_price, trade_date) - 1 as period_return,
               arg_max(close_price, trade_date) as last_close,
               sum(turnover) as turnover
        from px group by all
        """,
        (start, hi, *sectors),
    )
    breadth = q(
        f"""
        select sum(advancers) as advancers, sum(decliners) as decliners from marts.mart_sector_daily
        where trade_date = ? and sector in ({sector_ph})
        """,
        (hi, *sectors),
    ).iloc[0]

    c1, c2, c3, c4 = st.columns(4)
    c1.metric("Securities", len(perf))
    c2.metric("Median period return", f"{perf['period_return'].median():+.1%}")
    c3.metric("Turnover (period)", f"₹{perf['turnover'].sum() / 1e12:,.2f} L Cr")
    c4.metric(
        "Advancers / Decliners (last day)",
        f"{int(breadth.advancers or 0)} / {int(breadth.decliners or 0)}",
    )

    left, right = st.columns([3, 2])
    with left:
        sector_perf = (
            perf.groupby("sector", as_index=False)["period_return"]
            .mean()
            .sort_values("period_return")
        )
        sector_perf["direction"] = sector_perf["period_return"].map(
            lambda r: "Up" if r >= 0 else "Down"
        )
        fig = px.bar(
            sector_perf,
            x="period_return",
            y="sector",
            orientation="h",
            color="direction",
            color_discrete_map={"Up": POSITIVE, "Down": NEGATIVE},
            title="Sector return (equal-weighted)",
            text_auto=".1%",
        )
        fig.update_xaxes(tickformat=".0%")
        fig.update_layout(showlegend=False, hovermode="closest")
        st.plotly_chart(style(fig), width="stretch")
    with right:
        st.markdown("**Top movers**")
        movers = perf.sort_values("period_return", ascending=False)
        show = pd.concat([movers.head(5), movers.tail(5)])[
            ["symbol", "sector", "last_close", "period_return"]
        ]
        st.dataframe(
            show,
            hide_index=True,
            width="stretch",
            column_config={
                "last_close": st.column_config.NumberColumn("Last close", format="₹%.2f"),
                "period_return": st.column_config.NumberColumn("Return", format="percent"),
            },
        )

    breadth_ts = q(
        f"""
        select trade_date, sum(advancers) - sum(decliners) as net_advancers
        from marts.mart_sector_daily
        where trade_date between ? and ? and sector in ({sector_ph})
        group by 1 order by 1
        """,
        (start, hi, *sectors),
    )
    breadth_ts["cumulative_ad_line"] = breadth_ts["net_advancers"].cumsum()
    fig = px.line(
        breadth_ts,
        x="trade_date",
        y="cumulative_ad_line",
        title="Advance–decline line (cumulative net advancers)",
        color_discrete_sequence=SERIES,
    )
    st.plotly_chart(style(fig, 300), width="stretch")

# ---------------------------------------------------------------- drill-down
with drill:
    universe = q(
        f"select symbol, company_name from marts.dim_security where sector in ({sector_ph}) order by 1",
        tuple(sectors),
    )
    symbol = st.selectbox(
        "Security",
        universe["symbol"],
        format_func=lambda s: f"{s} — {universe.set_index('symbol').at[s, 'company_name']}",
    )
    ti = q(
        """
        select * from marts.mart_technical_indicators
        where symbol = ? and trade_date between ? and ? order by trade_date
        """,
        (symbol, start, hi),
    )
    last = ti.iloc[-1]
    k1, k2, k3, k4 = st.columns(4)
    k1.metric("Close", f"₹{last.close_price:,.2f}")
    k2.metric(
        "RSI (14)", f"{last.rsi_14:.0f}" if pd.notna(last.rsi_14) else "—", last.rsi_signal or ""
    )
    k3.metric(
        "20d volatility (ann.)",
        f"{last.volatility_20d_annualised:.1%}"
        if pd.notna(last.volatility_20d_annualised)
        else "—",
    )
    k4.metric(
        "From 52w high", f"{last.pct_from_52w_high:+.1%}", last.trend_regime.replace("_", " ")
    )

    long = ti.melt(
        "trade_date", ["close_price", "sma_50", "sma_200"], var_name="series", value_name="price"
    )
    long["series"] = long["series"].map(
        {"close_price": "Close", "sma_50": "SMA 50", "sma_200": "SMA 200"}
    )
    fig = px.line(
        long,
        x="trade_date",
        y="price",
        color="series",
        color_discrete_sequence=SERIES,
        title=f"{symbol} price & moving averages (₹)",
    )
    st.plotly_chart(style(fig, 400), width="stretch")

    fig = px.line(ti, x="trade_date", y="rsi_14", title="RSI (14)", color_discrete_sequence=SERIES)
    for level, label in ((70, "Overbought 70"), (30, "Oversold 30")):
        fig.add_hline(
            y=level,
            line_dash="dot",
            line_color=NEUTRAL,
            line_width=1,
            annotation_text=label,
            annotation_position="top left",
        )
    fig.update_yaxes(range=[0, 100])
    st.plotly_chart(style(fig, 240), width="stretch")

    with st.expander("Data table"):
        st.dataframe(ti, hide_index=True, width="stretch")

# ---------------------------------------------------------------- data quality
with dq:
    runs = q(
        """
        select distinct run_id, started_at, data_source, start_date, end_date, status,
               rows_ingested, rows_valid, rows_quarantined, rows_duplicate
        from marts.mart_data_quality order by started_at desc
        """
    )
    total_in = runs["rows_ingested"].sum()
    d1, d2, d3, d4 = st.columns(4)
    d1.metric("Pipeline runs", len(runs))
    d2.metric("Rows ingested", f"{total_in:,}")
    d3.metric(
        "Quarantined",
        f"{runs['rows_quarantined'].sum():,}",
        f"{runs['rows_quarantined'].sum() / max(total_in, 1):.2%} of input",
        delta_color="off",
    )
    d4.metric("Failed runs", int((runs["status"] == "failed").sum()))

    rules = q(
        """
        select rule_name, any_value(rule_description) as description, any_value(severity) as severity,
               sum(rows_failed) as rows_failed
        from marts.mart_data_quality where rule_name is not null
        group by 1 order by rows_failed desc
        """
    )
    fig = px.bar(
        rules.sort_values("rows_failed"),
        x="rows_failed",
        y="rule_name",
        orientation="h",
        title="Rows flagged per rule (all runs)",
        hover_data=["description", "severity"],
        color_discrete_sequence=[STATUS_BAD],
        text_auto=True,
    )
    fig.update_layout(hovermode="closest")
    st.plotly_chart(style(fig, 340), width="stretch")

    st.markdown("**Run history**")
    st.dataframe(runs, hide_index=True, width="stretch")

    qdir = WAREHOUSE.parent / "quarantine" / "prices"
    if any(qdir.glob("*/*.parquet")):
        st.markdown("**Quarantine sample** — rows held back from silver, with reasons")
        sample = q(
            f"""
            select trade_date, symbol, open, high, low, close, volume, dq_reasons, run_id
            from read_parquet('{qdir.as_posix()}/*/*.parquet', hive_partitioning = true)
            order by trade_date desc limit 200
            """
        )
        st.dataframe(sample, hide_index=True, width="stretch")

